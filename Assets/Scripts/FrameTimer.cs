using UnityEngine;

/// <summary>
/// ⏱️ **フレームの細かさに左右されない間隔の数え方**（数理設計 P1・2026-09-28）。
///
/// <para>
/// ⚠⚠ **なぜ要るか（実測）**：攻撃・湧き・回復の間隔を「間隔に達したら 0 に戻す」で数えていた。
///   これだと1フレームの長さ（dt）ぶんの端数が毎回捨てられ、**1フレームが粗いほど間隔が伸びる**。
///   16倍・60fps なら dt≈0.27秒 ＝ 0.35秒おきのはずの着弾が約0.54秒おきに間延びする。
///   計測専用モードで「同じ設定なのに結果がずれる（p=0.022）」「16倍がわずかに守り有利」の原因。
///   等速60fpsでは1%未満だが、4倍で遊ぶ人には数%効く（ゲーム本体の不具合）。
/// </para>
/// <para>
/// 直し方：間隔を超えた端数を**次へ持ち越す**。ただし持ち越すのは**1フレームぶん（dt）まで**
///   ―― 待っている間（射程外など）に溜まった分で連射しないように。
/// </para>
/// </summary>
public static class FrameTimer
{
    /// <summary>発火した後のタイマーの値（0 に戻す代わりに使う）。</summary>
    public static float Carry(float timer, float interval)
        => Mathf.Clamp(timer - interval, 0f, Time.deltaTime);
}
